"""
Two implementations of the same analytical query -- market share and
quarter-over-quarter growth per state/product/payer -- executed for real
against the local DuckDB warehouse:

  naive_market_share_growth(con)  -- nested, correlated subqueries, the
      kind of SQL that recomputes the same aggregate once per outer row.
  cte_market_share_growth(con)    -- the CTE-refactored version: each
      aggregate is computed once in a named CTE and joined, with window
      functions used for the growth calculation instead of a self-join.

Both must produce identical result sets (checked in tests/test_pipeline.py).
Runtime is measured for real with time.perf_counter() in run_all.py / the
tests -- no numbers here are asserted without being generated by an actual
query execution against the 1M+-row table.
"""

from sql_local.warehouse import TABLE_NAME

NAIVE_SQL = f"""
SELECT DISTINCT
    t.state, t.year, t.quarter_num, t.quarter_index, t.product_name,
    (SELECT SUM(s2.rx_count) FROM {TABLE_NAME} s2
     WHERE s2.state = t.state AND s2.year = t.year AND s2.quarter_num = t.quarter_num
       AND s2.product_name = t.product_name) AS product_rx,
    (SELECT SUM(s3.rx_count) FROM {TABLE_NAME} s3
     WHERE s3.state = t.state AND s3.year = t.year AND s3.quarter_num = t.quarter_num) AS total_rx,
    (SELECT SUM(s4.rx_count) FROM {TABLE_NAME} s4
     WHERE s4.state = t.state AND s4.product_name = t.product_name
       AND s4.quarter_index = t.quarter_index - 1) AS prev_quarter_rx
FROM {TABLE_NAME} t
ORDER BY t.state, t.year, t.quarter_num, t.product_name
"""

CTE_SQL = f"""
WITH state_quarter_totals AS (
    SELECT state, year, quarter_num, quarter_index,
           SUM(rx_count) AS total_rx
    FROM {TABLE_NAME}
    GROUP BY state, year, quarter_num, quarter_index
),
product_quarter_totals AS (
    SELECT state, year, quarter_num, quarter_index, product_name,
           SUM(rx_count) AS product_rx
    FROM {TABLE_NAME}
    GROUP BY state, year, quarter_num, quarter_index, product_name
),
market_share AS (
    SELECT p.state, p.year, p.quarter_num, p.quarter_index, p.product_name,
           p.product_rx, s.total_rx
    FROM product_quarter_totals p
    JOIN state_quarter_totals s
      ON p.state = s.state AND p.quarter_index = s.quarter_index
),
with_growth AS (
    SELECT *,
           LAG(product_rx) OVER (
               PARTITION BY state, product_name ORDER BY quarter_index
           ) AS prev_quarter_rx
    FROM market_share
)
SELECT state, year, quarter_num, quarter_index, product_name, product_rx, total_rx, prev_quarter_rx
FROM with_growth
ORDER BY state, year, quarter_num, product_name
"""


def naive_market_share_growth(con):
    return con.execute(NAIVE_SQL).fetchdf()


def cte_market_share_growth(con):
    return con.execute(CTE_SQL).fetchdf()
